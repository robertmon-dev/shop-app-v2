import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

const SPEC = "../../apps/api/swagger/v1/swagger.yaml";
const ZOD = "src/zod/zod.gen.ts";
const OUT = "src/registry.gen.ts";
const METHODS = ["get", "post", "put", "patch", "delete"];

const capitalize = (word) => word.charAt(0).toUpperCase() + word.slice(1);

const capitalizeToken = (token) =>
  /^\d/.test(token)
    ? token.replace(
        /^(\d+)([a-z])/,
        (_, digits, letter) => digits + letter.toUpperCase(),
      )
    : capitalize(token);

const pascal = (text) =>
  text
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map(capitalizeToken)
    .join("");

const segmentName = (segment) =>
  segment.startsWith("{") ? `By${pascal(segment)}` : pascal(segment);

const baseName = (method, path) =>
  `z${capitalize(method)}${path.split("/").filter(Boolean).map(segmentName).join("")}`;

const exportedNames = () =>
  new Set(
    [...readFileSync(ZOD, "utf8").matchAll(/^export const (\w+) =/gm)].map(
      (m) => m[1],
    ),
  );

const operations = (spec) =>
  Object.entries(spec.paths).flatMap(([path, item]) =>
    METHODS.filter((method) => item[method]).map((method) => ({
      method,
      path,
    })),
  );

const entry = ({ method, path }, names) => {
  const base = baseName(method, path);
  const request = names.has(`${base}Data`) ? `${base}Data` : null;
  const response = names.has(`${base}Response`) ? `${base}Response` : null;
  if (!request)
    throw new Error(
      `No request schema found for ${method} ${path} (${base}Data)`,
    );
  return { key: `${method} ${path}`, request, response };
};

const render = ({ key, request, response }) =>
  `  "${key}": { request: z.${request}, response: ${response ? `z.${response}` : "null"} },`;

const main = () => {
  const names = exportedNames();
  const entries = operations(parse(readFileSync(SPEC, "utf8"))).map((op) =>
    entry(op, names),
  );
  const body = entries.map(render).join("\n");
  writeFileSync(
    OUT,
    `// This file is auto-generated by scripts/registry.mjs\n\nimport * as z from "./zod/zod.gen";\n\nexport const operationSchemas = {\n${body}\n} as const;\n`,
  );
};

main();
